CREATE EXTENSION IF NOT EXISTS citext;

-- Search document for a title: romaji/English names weigh most, then the native name, then
-- synonyms. The 'simple' configuration is used on purpose: titles are names in mixed languages,
-- so no stemming or stop words. Declared IMMUTABLE so it can back a generated column
-- (array_to_string is only STABLE in general, but is deterministic for text[]).
CREATE FUNCTION title_search_vector(romaji text, english text, native text, synonyms text[])
RETURNS tsvector
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
AS $$
    SELECT setweight(to_tsvector('simple'::regconfig, coalesce(romaji, '')), 'A')
        || setweight(to_tsvector('simple'::regconfig, coalesce(english, '')), 'A')
        || setweight(to_tsvector('simple'::regconfig, coalesce(native, '')), 'B')
        || setweight(to_tsvector('simple'::regconfig, coalesce(array_to_string(synonyms, ' '), '')), 'C')
$$;

