--       allows DELETE and TRUNCATE, e.g. DELETE FROM "user" cascading to the user's events.
--   SELECT set_config('akiba.event_maintenance', 'merge', true);   -- title merge (doc 05 §5)
--       allows UPDATE of "title_id", "entry_id" and "run_id" only (repointing); who did what,
--       when, and the payload stay immutable.
--
-- This guards against application bugs and stray SQL. It is not a security boundary against a
-- role that may set that parameter or disable triggers.
CREATE FUNCTION event_append_only_guard() RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    mode text := coalesce(current_setting('akiba.event_maintenance', true), '');
BEGIN
    IF TG_OP = 'DELETE' AND mode = 'purge' THEN
        RETURN OLD;
    END IF;
    IF TG_OP = 'TRUNCATE' AND mode = 'purge' THEN
        RETURN NULL;
    END IF;
    IF TG_OP = 'UPDATE' AND mode = 'merge'
        AND (NEW.id, NEW.user_id, NEW.type, NEW.payload, NEW.occurred_at, NEW.created_at)
            IS NOT DISTINCT FROM
            (OLD.id, OLD.user_id, OLD.type, OLD.payload, OLD.occurred_at, OLD.created_at)
    THEN
        RETURN NEW;
    END IF;
    RAISE EXCEPTION 'event is append-only: % is not allowed', TG_OP
        USING ERRCODE = 'AKB01',
              HINT = 'Record a correction as a new event. Account purge and title merge must opt in with akiba.event_maintenance.';
END;
$$;

CREATE TRIGGER "event_append_only_row"
    BEFORE UPDATE OR DELETE ON "event"
    FOR EACH ROW EXECUTE FUNCTION event_append_only_guard();

CREATE TRIGGER "event_append_only_truncate"
    BEFORE TRUNCATE ON "event"
    FOR EACH STATEMENT EXECUTE FUNCTION event_append_only_guard();
